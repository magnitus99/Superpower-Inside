import esbuild from 'esbuild';
import process from 'process';
import { copyFile, mkdir, readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { ARTIFACT_PATHS } from './scripts/artifact-paths.mjs';
import { builtinModules } from 'node:module';
import { mcpStdioNodeTimers } from './scripts/mcp-stdio-build.mjs';
import {
  MAIN_JS_SIZE_LIMIT_BYTES,
  assertMainJsSize,
  needsStrongBundleOptimization,
} from './scripts/bundle-size-policy.mjs';

const banner =
  `/*\n` +
  `THIS IS A GENERATED/BUNDLED FILE BY ESBUILD\n` +
  `if you want to view the source, please visit the github repository of this plugin\n` +
  `*/`;

const prod = process.argv[2] === 'production';

const outfile = `${ARTIFACT_PATHS.plugin}/main.js`;
await mkdir(ARTIFACT_PATHS.plugin, { recursive: true });
const sourceAssets = ['manifest.json', 'styles.css', 'THIRD_PARTY_NOTICES.md'];
const pluginAssets = {
  name: 'plugin-source-assets',
  setup(builder) {
    builder.onLoad({ filter: /[/\\]main\.ts$/ }, async ({ path }) => ({
      contents: await readFile(path, 'utf8'),
      loader: 'ts',
      resolveDir: dirname(path),
      watchFiles: sourceAssets.map((file) => resolve(file)),
    }));
    builder.onEnd(async ({ errors }) => {
      if (errors.length) return;
      await Promise.all(sourceAssets.map(
        (file) => copyFile(file, `${ARTIFACT_PATHS.plugin}/${file}`),
      ));
    });
  },
};

const buildOptions = {
  banner: { js: banner },
  entryPoints: ['main.ts'],
  bundle: true,
  plugins: [mcpStdioNodeTimers, pluginAssets],
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    ...builtinModules,
    ...builtinModules.map((moduleName) => `node:${moduleName}`),
  ],
  format: 'cjs',
  target: 'es2022',
  // 문자열 값의 공백은 보존하고 출력 파일에는 이스케이프된 문자열로 기록합니다.
  supported: { 'template-literal': false },
  logLevel: 'info',
  treeShaking: true,
  outfile,
  // 개발 빌드에서만 채팅 추적 기록을 허용합니다. 배포 번들은 항상 false로 접힙니다.
  define: { __SUPERPOWER_DEBUG_TRACE__: prod ? 'false' : 'true' },
};

if (prod) {
  const buildProduction = (strongOptimization) =>
    esbuild.build({
      ...buildOptions,
      sourcemap: false,
      minify: true,
      drop: ['debugger'],
      metafile: true,
      charset: strongOptimization ? 'utf8' : 'ascii',
      legalComments: strongOptimization ? 'none' : 'eof',
    });

  let result = await buildProduction(false);
  let output = result.metafile.outputs[outfile];
  if (!output) throw new Error('esbuild did not report main.js output metadata.');

  if (needsStrongBundleOptimization(output.bytes)) {
    console.warn(
      `main.js is ${output.bytes.toLocaleString('en-US')} bytes, above the ${MAIN_JS_SIZE_LIMIT_BYTES.toLocaleString('en-US')}-byte budget. Rebuilding with the strong optimization profile.`,
    );
    result = await buildProduction(true);
    output = result.metafile.outputs[outfile];
    if (!output) throw new Error('esbuild did not report optimized main.js output metadata.');
  }

  try {
    assertMainJsSize(output.bytes);
  } catch (error) {
    const contributors = Object.entries(output.inputs)
      .sort((left, right) => right[1].bytesInOutput - left[1].bytesInOutput)
      .slice(0, 10)
      .map(
        ([file, metadata]) =>
          `${metadata.bytesInOutput.toLocaleString('en-US').padStart(12)}  ${file}`,
      )
      .join('\n');
    console.error(`Largest main.js contributors:\n${contributors}`);
    throw error;
  }

  console.log(
    `Build complete. main.js: ${output.bytes.toLocaleString('en-US')} / ${MAIN_JS_SIZE_LIMIT_BYTES.toLocaleString('en-US')} bytes.`,
  );
  process.exit(0);
}

// 일회성 개발 빌드: 추적 기록이 켜진 번들을 만듭니다(릴리스 번들과 분리).
if (process.argv[2] === 'dev') {
  await esbuild.build({
    ...buildOptions,
    sourcemap: false,
    minify: false,
    drop: [],
  });
  console.log('Dev build complete. Debug trace is enabled in this bundle.');
  process.exit(0);
}

const context = await esbuild.context({
  ...buildOptions,
  sourcemap: 'inline',
  minify: false,
  drop: [],
});
await context.watch();
