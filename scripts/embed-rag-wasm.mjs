#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync, gunzipSync } from 'node:zlib';

// 런타임 복원 함수와 같은 고정 예산입니다.
const MAX_WASM_BYTES = 8 * 1024 * 1024;
const MAX_GZIP_BYTES = 4 * 1024 * 1024;
const [, , wasmPathArg, outputPathArg, ...extraArgs] = process.argv;

if (!wasmPathArg || !outputPathArg || extraArgs.length) {
  console.error('Usage: node scripts/embed-rag-wasm.mjs <input.wasm> <output.ts>');
  process.exit(1);
}

try {
  const wasmPath = path.resolve(wasmPathArg);
  const outputPath = path.resolve(outputPathArg);
  const size = statSync(wasmPath).size;
  if (size < 8 || size > MAX_WASM_BYTES) throw new Error('WASM 크기 예산 초과 또는 빈 입력');
  const wasm = readFileSync(wasmPath);
  if (
    wasm.length !== size ||
    wasm.readUInt32LE(0) !== 0x6d736100 ||
    wasm.readUInt32LE(4) !== 1 ||
    !WebAssembly.validate(wasm)
  )
    throw new Error('유효하지 않은 WASM 입력');

  const gzip = gzipSync(wasm, { level: 9 });
  gzip.writeUInt32LE(0, 4); // mtime을 고정해 같은 입력의 생성물을 결정적으로 유지합니다.
  gzip[9] = 255; // 호스트 OS 표식을 제거합니다.
  if (gzip.length > MAX_GZIP_BYTES) throw new Error('gzip 크기 예산 초과');
  if (!gunzipSync(gzip).equals(wasm)) throw new Error('gzip 원본 복원 불일치');
  const sha256 = createHash('sha256').update(wasm).digest('hex');
  let checksum = 2166136261;
  for (const byte of gzip) checksum = Math.imul(checksum ^ byte, 16777619) >>> 0;
  const chunks = gzip.toString('base64').match(/.{1,100}/g) ?? [];
  const helperPath = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    '../src/rag/wasm-payload',
  );
  const relativeHelper = path.relative(path.dirname(outputPath), helperPath).replaceAll('\\', '/');
  const helperImport = relativeHelper.startsWith('.') ? relativeHelper : `./${relativeHelper}`;
  const content = [
    '// Generated by scripts/build-rag-wasm.fish. Do not edit by hand.',
    `// 원본 WASM: ${wasm.length} bytes; SHA-256: ${sha256}`,
    `// 내장 gzip: ${gzip.length} bytes; 복원은 모듈 평가당 한 번이며 base64 문자열만 유지합니다.`,
    `import { restoreWasmBase64 } from ${JSON.stringify(helperImport)};`,
    'export const RAG_WASM_BASE64 = restoreWasmBase64([',
    ...chunks.map((chunk) => `  '${chunk}',`),
    `].join(''), ${wasm.length}, ${checksum});`,
    '',
  ].join('\n');

  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, content);
} catch (error) {
  console.error('WASM 압축 내장 생성 실패:', error);
  process.exitCode = 1;
}
