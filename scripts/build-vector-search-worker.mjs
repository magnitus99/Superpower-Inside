import { build } from 'esbuild';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(root, 'generated/vector-search-worker-source.ts');
const result = await build({
  entryPoints: [resolve(root, 'src/rag/vector-search-worker-entry.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
});
const output = result.outputFiles?.[0]?.text;
if (!output) throw new Error('Vector search worker bundle was not generated.');
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// This file is generated by scripts/build-vector-search-worker.mjs. Do not edit it directly.\nexport const VECTOR_SEARCH_WORKER_SOURCE = ${JSON.stringify(output)};\n`,
  'utf8',
);
